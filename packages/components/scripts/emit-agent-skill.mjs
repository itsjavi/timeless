/**
 * Everything the consumer agent skill and the index files are made of.
 *
 * Two sources, and neither is hand-maintained prose:
 *
 * - `component-registry.mjs` supplies the facts — every root, its attributes, its parts, its
 *   stylesheets — and the stylesheets are proven against it by `validate-contracts.mjs`.
 * - `authoring-grammar.mjs` supplies the grammar, declared once and projected into every consumer.
 *
 * `pnpm generate:check` fails the build the moment any generated copy drifts from either source.
 *
 * Value *names* only, never value *lists*. An agent that needs the permitted values fetches the
 * component's `.md` page, which is generated from the same contracts. Keeping the lists out is what
 * holds this file to a few kilobytes, which is the whole point of a skill reference.
 */

import { grammarRules, renderGrammar, summary } from './authoring-grammar.mjs'

/** `set` names the exported `as const` array; without one the attribute takes free-form input. */
const attributeSummary = (attribute) => {
  const name = `\`${attribute.name}\``
  if (attribute.set) return `${name} (\`${attribute.set}\`)`
  if (attribute.type === 'boolean') return `${name} (presence)`
  return `${name} (any ${attribute.type})`
}

const cell = (text) => text.replace(/\|/g, '\\|')

const table = (headers, rows) => [
  `| ${headers.join(' | ')} |`,
  `| ${headers.map(() => '---').join(' | ')} |`,
  ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`),
  '',
]

const attributeCell = (contract) =>
  contract.attributes.length === 0 ? 'none' : contract.attributes.map(attributeSummary).join(', ')

const partCell = (contract) =>
  contract.parts.length === 0
    ? 'none'
    : contract.parts.map((part) => `\`${part.name}\`${part.required ? '*' : ''}`).join(', ')

export function createSkillContracts(components, valueSets) {
  const css = components.filter((contract) => contract.kind === 'css')
  const elements = components.filter((contract) => contract.kind === 'custom-element')

  const lines = [
    '# Timeless UI component contracts',
    '',
    '<!-- Generated by packages/components/scripts/generate-elements.mjs. Do not edit. -->',
    '',
    `Every public root in the library: ${css.length} CSS components and ${elements.length} custom`,
    'elements. Attribute values are named by their exported value set rather than listed — import the',
    'set to enumerate it, or fetch the component page for the full contract.',
    '',
    '**A root name is not a page slug.** One page often documents several roots — `ui-input`,',
    '`ui-textarea`, `ui-label`, and `ui-error` are all on the Field page — so',
    '`https://timeless.build/docs/components/<root-without-the-ui-prefix>.md` is a guess, and for',
    'those roots it is a 404. Take the real route from `https://timeless.build/llms.txt`, which lists',
    'every page, or browse `https://timeless.build/docs/components/`.',
    '',
    'Parts marked `*` are required for the component to work.',
    '',
    '## CSS components',
    '',
    'A native element with the root class. Configure with `data-ui-*` attributes. Nothing to register.',
    '',
    ...table(
      ['Root', 'Configuration', 'Parts'],
      css.map((contract) => [
        `\`${contract.root.name}\`${contract.root.kind === 'selector' ? ' (selector)' : ''}`,
        attributeCell(contract),
        partCell(contract),
      ]),
    ),
    '## Custom elements',
    '',
    'A registered host wrapping your own markup. Configure with plain attributes, never `data-ui-*`.',
    'Register each element you use by importing `@timelessui/components/register/<tag>`, which',
    'registers as it is imported, or by calling the function that',
    '`@timelessui/components/define/<tag>` exports.',
    '',
    ...table(
      ['Element', 'Attributes', 'Parts'],
      elements.map((contract) => [
        `\`<${contract.root.name}>\``,
        attributeCell(contract),
        partCell(contract),
      ]),
    ),
    '## Value sets',
    '',
    'The permitted values behind every `set` named above. Each is also exported from the package root',
    'as an `as const` array — import the array rather than retyping a list.',
    '',
    ...table(
      ['Set', 'Values'],
      Object.entries(valueSets).map(([name, set]) => [
        `\`${name}\``,
        set.values.map((value) => `\`${value}\``).join(' · '),
      ]),
    ),
    '## Stylesheets',
    '',
    'Import from `@timelessui/components/css/<file>`. `tokens.css` and the `core/` file are required; the `themes/atmosphere/` file is the optional look.',
    '',
    ...table(
      ['Root', 'Stylesheets'],
      components.map((contract) => [
        `\`${contract.root.name}\``,
        contract.css.map((file) => `\`${file}\``).join(', '),
      ]),
    ),
  ]

  return `${lines.join('\n').trim()}\n`
}

/**
 * The canonical grammar as a standalone Markdown file.
 *
 * It ships inside the skill directory, which puts it in the published package, and `apps/web` reads it
 * at build time for the `/llms.txt` preamble and the paste-able block on the agents page. That read is
 * why it exists as a file rather than only inline in `SKILL.md`: the website must not parse prose out
 * of another document, and it must not keep a second copy.
 */
export function createGrammarMarkdown() {
  return `${[
    '# Timeless UI authoring grammar',
    '',
    '<!-- Generated by packages/components/scripts/generate-elements.mjs. Do not edit. -->',
    '',
    ...summary.split('\n').map((line) => `> ${line}`),
    '',
    renderGrammar({ heading: 2 }),
  ]
    .join('\n')
    .trim()}\n`
}

