/**
 * `context7.json`, which Context7 reads to index this repository.
 *
 * Generated because its `rules` array is the grammar in imperative form, and a hand-written copy was
 * the fourth place the grammar lived. `folders` and `excludeFolders` are indexing configuration rather
 * than grammar, so they are declared here.
 */
export function createContext7Config() {
  return {
    $schema: 'https://context7.com/schema/context7.json',
    projectTitle: 'Timeless UI',
    description: summary.replace(/\n/g, ' '),
    folders: ['apps/web/src/content/docs', 'packages/components/skills'],
    excludeFolders: [
      'apps/e2e',
      'apps/stories',
      'packages/core/src',
      'packages/components/src',
      'packages/components/dist',
      'packages/examples/src',
      '.agents',
    ],
    rules: grammarRules(),
  }
}

/**
 * The block a consumer pastes into their own `AGENTS.md`.
 *
 * The imperative one-liners rather than the prose, because this is read inside someone else's
 * always-loaded instructions file where every line costs them context. The prose version is a fetch
 * away at the URL the block ends with.
 */
export function createAgentsBlockMarkdown() {
  return `${[
    '<!-- Generated by packages/components/scripts/generate-elements.mjs. Do not edit. -->',
    '',
    '## Timeless UI',
    '',
    ...grammarRules().map((rule) => `- ${rule}`),
  ]
    .join('\n')
    .trim()}\n`
}
